"""Produce real, reproducible demo results.

Runs the full campaign against the local reference and buggy SUTs (in-process
transport), then writes a human-readable summary to docs/RESULTS.md and keeps
the SQLite evidence + replay scripts under artifacts/.
"""
from __future__ import annotations

import asyncio
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from mdbt.campaign import run_campaign
from mdbt.executor import InProcessTransport
from mdbt.services.buggy import create_app as create_buggy
from mdbt.services.reference import create_app as create_reference
from mdbt.spec import load_spec_file
from mdbt.storage import EvidenceStore


DB_PATH = "artifacts/demo_evidence.db"
REPLAY_DIR = "artifacts/replays"
RESULT_DOC = "docs/RESULTS.md"


async def run_one(name, factory, seed=20261007, fuzz_steps=40, run_id=None):
    with EvidenceStore(DB_PATH) as store:
        run_id = run_id or f"run-demo-{name}"
        result = await run_campaign(
            spec=load_spec_file("fixtures/order_machine.json"),
            sut_name=name,
            transport_factory=lambda: InProcessTransport(factory()),
            store=store,
            run_id=run_id,
            seed=seed,
            fuzz_steps=fuzz_steps,
            replay_dir=REPLAY_DIR,
        )
        run_header = store.get_run(run_id)
        steps = store.get_steps(run_id)
        findings = store.get_findings(run_id)
    return result, run_header, steps, findings


async def main():
    suffix = __import__("datetime").datetime.now().strftime("%H%M%S")
    ref = await run_one(
        "reference", create_reference, run_id=f"run-demo-reference-{suffix}"
    )
    buggy = await run_one(
        "buggy", create_buggy, run_id=f"run-demo-buggy-{suffix}"
    )

    lines = []
    lines.append("# Real Run Results")
    lines.append("")
    lines.append(
        "Generated by `scripts/generate_results.py` "
        "(seed `20261007`, 17 guided + 40 fuzz steps per SUT)."
    )
    lines.append("")

    for label, (result, header, steps, findings) in [
        ("Reference service (correct)", ref),
        ("Buggy service (planted stateful defects)", buggy),
    ]:
        s = result["summary"]
        lines.append(f"## {label}")
        lines.append("")
        lines.append(f"- run id: `{result['run_id']}`")
        lines.append(f"- status: `{result['status']}`")
        lines.append(f"- steps executed: {s['steps_executed']}")
        lines.append(f"- consistent steps: {s['consistent_steps']}")
        lines.append(f"- discrepancy steps: {s['discrepancy_steps']}")
        lines.append(f"- findings: {s['findings']}")
        lines.append(f"- finding categories: {s['finding_categories']}")
        lines.append(f"- model resyncs: {s['resyncs']}")
        lines.append("")
        if findings:
            lines.append("| # | category | trigger | model state | minimised length |")
            lines.append("|---|----------|---------|-------------|------------------|")
            for i, f in enumerate(findings):
                lines.append(
                    f"| {i} | {f['category']} | `{f['command']['action']}` "
                    f"| `{f['expected']['reason']}` "
                    f"| {f['reduced_length']} |"
                )
            lines.append("")
            lines.append("Rationale for the first finding:")
            lines.append("")
            lines.append(f"> {findings[0]['rationale']}")
            lines.append("")

    # Record one full step as evidence of the recorded judgement inputs.
    _, _, buggy_steps, _ = buggy
    trigger = next(
        s for s in buggy_steps if s["verdict"]["kind"] == "discrepancy"
    )
    lines.append("## Example Trigger Evidence")
    lines.append("")
    lines.append("```json")
    lines.append(json.dumps(trigger, indent=2, ensure_ascii=False))
    lines.append("```")
    lines.append("")
    lines.append(
        f"Replay scripts: see `{REPLAY_DIR}/{buggy[0]['run_id']}_f*.py`."
    )
    lines.append("")

    Path(RESULT_DOC).write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {RESULT_DOC}")
    print("reference findings:", ref[0]["summary"]["findings"])
    print("buggy findings:", buggy[0]["summary"]["findings"])


if __name__ == "__main__":
    asyncio.run(main())
