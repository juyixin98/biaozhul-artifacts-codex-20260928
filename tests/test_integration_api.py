"""Integration tests through the FastAPI interface with local fixture
programs. Expected minimized sets are hand-computed reference answers:
in overflow_input.json only {m1, a1, a2} (mode=1, 70 + 30 = 100) meets
all trigger conditions of sum_threshold_crash.py."""
from __future__ import annotations

from tests.conftest import make_spec


def run_job(client, spec, **run_kwargs):
    created = client.post("/jobs", json=spec)
    assert created.status_code == 201
    job_id = created.json()["job_id"]
    client.post(f"/jobs/{job_id}/run", params=run_kwargs)
    return job_id


def test_full_reduction_reproduces_target_error(client):
    job_id = run_job(client, make_spec("sum_threshold_crash.py", "overflow_input.json"))
    report = client.get(f"/jobs/{job_id}/report").json()
    assert report["state"] == "done"
    assert report["verdict"] == "target"
    # hand-computed reference answer, not generated by the core
    assert sorted(report["minimized_record_ids"]) == ["a1", "a2", "m1"]
    assert report["original_size"] == 8
    assert report["minimized_size"] == 3
    # 1-minimality: removing any remaining record no longer deterministically fails
    assert report["one_minimal"] is True
    assert all(c["verdict"] != "target" for c in report["one_minimal_checks"])
    assert sorted(c["removed"] for c in report["one_minimal_checks"]) == ["a1", "a2", "m1"]
    # scope is stated honestly: 1-minimal under record removal, not global
    assert "record-removal" in report["minimality_scope"]
    assert "not a claim of global minimality" in report["minimality_scope"]
    # candidates keep the declared syntax constraints
    ids = [r["id"] for r in report["minimized_input"]["records"]]
    assert len(ids) == len(set(ids)) == 3


def test_cache_is_shared_across_jobs(client):
    spec = make_spec("sum_threshold_crash.py", "overflow_input.json")
    first = client.get(f"/jobs/{run_job(client, spec)}/report").json()
    second = client.get(f"/jobs/{run_job(client, spec)}/report").json()
    assert first["live_executions"] > 0
    # second identical job is served entirely from the cache
    assert second["live_executions"] == 0
    assert second["cache_hits"] > 0
    assert sorted(second["minimized_record_ids"]) == ["a1", "a2", "m1"]


def test_indeterminate_initial_input_fails_job(client):
    spec = make_spec("hang_on_marker.py", "hang_input.json", timeout=0.5)
    job_id = run_job(client, spec)
    report = client.get(f"/jobs/{job_id}/report").json()
    assert report["state"] == "failed"
    assert "indeterminate" in report["error"]


def test_malformed_program_exit_is_other_error(client):
    # exit code 2 (malformed) is neither target nor pass: classifier unit
    # tests cover the mapping; here the hang program without a hang record
    # simply passes, so the job fails the initial reproduction check.
    spec = make_spec("hang_on_marker.py", "overflow_input.json", timeout=2.0)
    job_id = run_job(client, spec)
    report = client.get(f"/jobs/{job_id}/report").json()
    assert report["state"] == "failed"
    assert "verdict=pass" in report["error"]


def test_events_carry_request_id_states_and_reasons(client):
    job_id = run_job(client, make_spec("sum_threshold_crash.py", "overflow_input.json"))
    events = client.get(f"/jobs/{job_id}/events").json()["events"]
    names = [e["event"] for e in events]
    assert names[0] == "job_created"
    assert "initial_check" in names and "run_finished" in names
    assert all(e["request_id"] for e in events)
    initial = next(e for e in events if e["event"] == "initial_check")
    assert initial["detail"]["verdict"] == "target"
    assert initial["detail"]["reason"]


def test_sensitive_fields_are_masked_in_events(client):
    job_id = run_job(client, make_spec("sum_threshold_crash.py", "overflow_input.json"))
    events = client.get(f"/jobs/{job_id}/events").json()["events"]
    created = next(e for e in events if e["event"] == "job_created")
    masked = created["detail"]["input_records_masked"]
    note = next(r for r in masked if r["id"] == "n1")
    assert note["secret"] == "***"
    assert "s3cr3t-token" not in str(events)


def test_unknown_job_is_404(client):
    assert client.get("/jobs/nope/report").status_code == 404
