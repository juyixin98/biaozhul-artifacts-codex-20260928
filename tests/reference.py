"""Independent formulas and constants used by tests.

These deliberately do not import the project's training kernel, so expected
gradient results are not generated by the code under test.
"""
from __future__ import annotations

import math


REFERENCE_CENTER = [0.10, -0.20, 0.30]
REFERENCE_POSITIVE = [0.40, 0.50, -0.60]
REFERENCE_NEGATIVE = [-0.70, 0.80, 0.90]
LEARNING_RATE = 0.25


def dot(a: list[float], b: list[float]) -> float:
    return sum(x * y for x, y in zip(a, b))


def sigmoid(x: float) -> float:
    if x >= 0:
        return 1.0 / (1.0 + math.exp(-x))
    ex = math.exp(x)
    return ex / (1.0 + ex)


def reference_step(
    center: list[float],
    target: list[float],
    label: float,
    learning_rate: float,
) -> dict:
    score = dot(center, target)
    probability = sigmoid(score)
    upstream = label - probability
    input_gradient = [learning_rate * upstream * x for x in target]
    output_gradient = [learning_rate * upstream * x for x in center]
    return {
        "score": score,
        "probability": probability,
        "upstream": upstream,
        "input_gradient": input_gradient,
        "output_gradient": output_gradient,
    }


def reference_keep_probability(frequency: float, threshold: float) -> float:
    return min(1.0, (math.sqrt(frequency / threshold) + 1.0) * threshold / frequency)
